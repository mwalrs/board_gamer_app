class AverageRatings {
  final double averageHost;
  final int reviewCountHost;

  final double averageFood;
  final int reviewCountFood;

  final double averageEvening;
  final int reviewCountEvening;

  const AverageRatings({
    required this.averageHost,
    required this.reviewCountHost,
    required this.averageFood,
    required this.reviewCountFood,
    required this.averageEvening,
    required this.reviewCountEvening,
  });
}